"""Новость по смыслу о факторе: метка разметки не должна спорить с заголовком.

Разметка новостей ставит фактор по ключевому слову («пошлин», «ставк», «спрос»), и случайное слово даёт
случайную связь: пошлина на вино — «санкции и ВЭД», ипотека — «стоимость заёмных денег», «ЦБ не спешит» —
«рынок труда». Правила по заголовку (до « // », без лида):
- `OFF`: заголовок о чём-то из первого списка и без слов самого фактора из второго — метка не по смыслу;
- `BLOCK`: потребительские товары (алкоголь, вино) — не тема фактора, если в заголовке нет сырья;
- `NEEDS`: фактору нужны его слова в заголовке, иначе новость не о нём (зерно — не картофель и коровы).
Ими пользуются оценка ленты, главная причина события, сюжеты недели и «сейчас» у фактора на карте рисков.
"""

import re

OFF: dict[str, tuple[re.Pattern, re.Pattern]] = {
    # ипотека и девелоперы — не стоимость денег компании, пока в заголовке нет ставки ЦБ и кредитов бизнеса
    "rate": (
        re.compile(r"ипотек"),
        re.compile(
            r"ключев\w* ставк|ставк\w* цб|(?<!\w)цб(?!\w)|банк\w* росси|кредит|(?<!\w)мсп(?!\w)|корпоративн"
            r"|(?:повышени|снижени|повыс|сниз)\w* ставк"
        ),
    ),
    # бензин и газ — не санкции и ВЭД, пока нет слов внешней торговли
    "ved_logistics": (
        re.compile(r"бензин|дизел|топлив|(?<!\w)азс|нефтепродукт|(?<!\w)газ\w*|(?<!\w)спг"),
        re.compile(
            r"санкц|экспорт|импорт|пошлин|таможн|границ|логист|платеж|(?<!\w)вэд|за рубеж|вывоз|ввоз|перевоз"
            r"|транспорт|поставк\w* (?:в|из) "
        ),
    ),
    "inflation": (
        re.compile(r"ипотек|новостро|девелопер|застройщик"),
        re.compile(r"инфляц|цены|подорожан|удорожан|индекс потребительских"),
    ),
    "consumer": (
        re.compile(r"ипотек|новостро|девелопер|застройщик"),
        re.compile(r"спрос|потреблен|продаж|розниц|покупател"),
    ),
}

# пошлины и санкции на потребительские товары — не внешняя торговля сырьём, даже со словом «пошлин»
BLOCK: dict[str, tuple[re.Pattern, re.Pattern]] = {
    "ved_logistics": (
        re.compile(r"алкогол|(?<!\w)вин[оау]\b|виноделы|виски|коньяк|пиво|падел|табак|сигарет"),
        re.compile(r"зерн|пшениц|нефт|металл|удобрен|уголь|газ\b"),
    ),
}

NEEDS: dict[str, re.Pattern] = {
    "commodity_agro": re.compile(
        r"зерн|пшениц|ячмен|кукуруз|подсолнечн|масличн|рапс|сахар|мук[аиу]\b|урожа|агро|сельхоз|продовольств"
        r"|продукт\w* питани|цены на (?:еду|продукт)|удобрен|элеватор|квот\w* на (?:вывоз|экспорт)"
    ),
    "labor": re.compile(
        r"труд|зарплат|занятост|безработ|кадр|вакан|мигрант|работник|персонал|оплат\w* труда|фот\b|найм"
    ),
}


def head(title: str) -> str:
    """Заголовок без лида: после « // » идёт текст, слова из которого не делают новость темой."""
    return title.split(" // ")[0].casefold().replace("ё", "е")


def title_about(title: str, code: str) -> bool:
    """Заголовок не спорит с меткой фактора `code` (см. модуль)."""
    low = head(title)
    for rules in (OFF, BLOCK):
        rule = rules.get(code)
        if rule is not None and rule[0].search(low) and not rule[1].search(low):
            return False
    need = NEEDS.get(code)
    return need is None or bool(need.search(low))
