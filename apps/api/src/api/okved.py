SECTOR_BY_CODE: dict[str, str] = {code: sector for sector, codes in _SECTORS.items() for code in codes}
SECTORS: list[str] = list(_SECTORS)

_CODE = re.compile(r"^\s*(\d{2})(?:\.\d+)*\s*$")


def okved_prefix(code: str | None) -> str | None:
    """Двузначный класс из кода вида `46.34`, `41.2` или `68.32.1`; мусор — None."""
    if not code:
        return None
    m = _CODE.match(code)
    return m.group(1) if m else None


def sector_for(code: str | None) -> str | None:
    prefix = okved_prefix(code)
    return SECTOR_BY_CODE.get(prefix) if prefix else None
