def render_materials(ctx: AgentContext) -> str:
    """Какие материалы банка найдены по заголовку события: по названию и дате модель выбирает запросы."""
    seen: dict[str, str] = {}
    for h in ctx.analytics:
        title = f"«{h.source.title[:90]}»" + (f" от {h.material_date:%d.%m.%Y}" if h.material_date else "")
        seen.setdefault(h.source.id.split("#", 1)[0], title)
    if not seen:
        return "Материалы банка по заголовку события: не найдены."
    return "Материалы банка по заголовку события:\n" + "\n".join(f"- {t}" for t in list(seen.values())[:6])


def plan_messages(ctx: AgentContext) -> list[dict]:
    body = "\n\n".join(
        [ctx.render_company(), ctx.render_exposure(), ctx.render_event(), render_materials(ctx)]
    )
    return [{"role": "system", "content": PLAN_SYSTEM}, {"role": "user", "content": body}]


def draft_messages(ctx: AgentContext) -> list[dict]:
    return [{"role": "system", "content": DRAFT_SYSTEM}, {"role": "user", "content": ctx.render()}]


def revise_messages(ctx: AgentContext, draft: Draft, report: Report, extra: str = "") -> list[dict]:
    issues = "\n".join(f"- {i.where()} · {i.check}: {i.message}" for i in report.issues)
    task = (
        "Самопроверка нашла проблемы в черновике. Исправь их и верни черновик целиком по той же схеме.\n"
        "Утверждение, которое нельзя подтвердить источником, убери или переформулируй как вывод (ai) или"
        " гипотезу (hypothesis) без цифр. Итог (verdict) и позицию банка (bank_position) сохрани и исправь,"
        " а не выбрасывай.\n"
        f"Проблемы:\n{issues}"
    )
    if extra:
        task += "\n" + extra
    return [
        {"role": "system", "content": DRAFT_SYSTEM},
        {"role": "user", "content": ctx.render()},
        {"role": "assistant", "content": dumps(draft.model_dump(mode="json", exclude_none=True))},
        {"role": "user", "content": task},
    ]
