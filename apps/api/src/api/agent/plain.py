"""Язык карточки: человек из бизнеса не должен видеть внутренних слов сервиса.

«Карта чувствительности», «канал», «фактор», «скор», коды вроде `demand_56`, ссылки `feat:`/`src:` — это язык
разработчика. Всё, что видит пользователь (итог, утверждения, действия, позиция банка, ход разбора,
предупреждения), проверяется здесь: самопроверка просит модель переписать, а служебные предупреждения с такими
словами остаются только в трассе.
"""

import re

_TECH = [
    (re.compile(r"карт\w* чувствительност\w*", re.IGNORECASE), "карта чувствительности"),
    (re.compile(r"\bканал(?:а|у|ом|е|ы|ов|ам|ами|ах)?\b", re.IGNORECASE), "канал"),  # в выводе — «через кого»
    # «факторинг» — продукт банка, его не трогаем
    (re.compile(r"\bфактор(?:а|у|ом|е|ы|ов|ам|ами|ах)?\b", re.IGNORECASE), "фактор"),
    # «скорее», «скоро», «скорость» — обычные слова; служебное — «скор», «скоринг»
    (re.compile(r"\bскор(?:а|у|ом|е|ы|ов)?\b|\bскоринг\w*", re.IGNORECASE), "скор"),
    (re.compile(r"\bрелевантн\w*", re.IGNORECASE), "релевантность"),
    (re.compile(r"\bэвристик\w*", re.IGNORECASE), "эвристика"),
    (re.compile(r"\bэмбеддинг\w*", re.IGNORECASE), "эмбеддинг"),
    # «токенизация активов» и ЦФА — банковская тема, служебное — только токены модели
    (re.compile(r"\b(?:LLM|GPT)\b|промпт\w*|токен\w* модел\w*", re.IGNORECASE), "служебное слово модели"),
    (re.compile(r"языков\w* модел\w*|нейросет\w*", re.IGNORECASE), "языковая модель"),
    (re.compile(r"\b(?:feat|src):\S*"), "служебная ссылка"),
    (re.compile(r"\b[A-Za-z]+_[A-Za-z0-9_]+\b"), "служебный код"),
    (re.compile(r"\b(?:rate|fx)\b"), "служебный код"),
    (re.compile(r"\bU_\d+\b"), "служебный номер компании"),
    (re.compile(r"(?<![\w.])r\s*=\s*-?\d"), "коэффициент r"),
]


# служебные предупреждения модулей данных → человеческим языком; что осталось служебным — пользователю не
# показываем
_HUMANIZE = [
    (
        re.compile(r"у события нет отраслей — цепочка через контрагентов не строится"),
        "в новости не названы отрасли — влияние через покупателей и поставщиков не оценить",
    ),
    (
        re.compile(r"платежи в выгрузке — ([\d,]+ %) выручки: цепочки не строим"),
        r"платежи в данных банка — лишь \1 выручки: влияние через контрагентов не оценить",
    ),
    (re.compile(r"\s*\(см\. gaps\)"), ""),
    (re.compile(r"в выгрузке"), "в данных банка"),
]
_TECH_NOTE = re.compile(r"цепочк\w*|\bgaps\b|выгрузк\w*|разметк\w*", re.IGNORECASE)


def humanize_note(text: str) -> str | None:
    """Предупреждение для пользователя: служебное переписываем, непереводимое — None (останется в трассе)."""
    for pattern, repl in _HUMANIZE:
        text = pattern.sub(repl, text)
    return text if is_plain(text) and not _TECH_NOTE.search(text) else None


# обычные слова, которые в языке сервиса стали служебными: в пересказе источника («Суэцкий канал», «ключевой
# фактор инфляции») они уместны
NATURAL = {"канал", "фактор"}


def technical(text: str, quoting: bool = False) -> list[str]:
    """Служебные слова в тексте для пользователя — названия найденного, без повторов.

    `quoting` — текст пересказывает источник (факт новости, позиция банка): обычные слова не считаем.
    """
    found = [
        name for pattern, name in _TECH if not (quoting and name in NATURAL) and pattern.search(text or "")
    ]
    return list(dict.fromkeys(found))


def is_plain(text: str) -> bool:
    return not technical(text)
